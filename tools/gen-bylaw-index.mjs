// Regenerates assets/bylaws-index.js from _bylaws/*.md (bylaws are immutable;
// re-run only if bylaws ever change).  node tools/gen-bylaw-index.mjs
import fs from "node:fs";
import path from "node:path";

const src = path.resolve("_bylaws");
const out = [];
for (const f of fs.readdirSync(src).filter(f => f.endsWith(".md")).sort()) {
  const md = fs.readFileSync(path.join(src, f), "utf8");
  const title = (md.match(/^title:\s*(.+)$/m) || [])[1]?.replace(/ Bylaws$/, "").trim();
  const category = (md.match(/^category:\s*(.+)$/m) || [])[1]?.trim();
  const rules = [...md.matchAll(/^## Rule (\d+) - (.+)$/gm)].map(m => ({ n: +m[1], name: m[2].trim() }));
  if (!title) continue;
  out.push({ slug: f.replace(/\.md$/, ""), title, category, rules });
}
const js = "// AUTO-GENERATED by tools/gen-bylaw-index.mjs — do not edit by hand.\n"
  + "// Source of truth: _bylaws/ (immutable). Regenerate with: node tools/gen-bylaw-index.mjs\n"
  + "var KENTISH_BYLAWS = " + JSON.stringify(out, null, 1) + ";\n"
  + "if (typeof module !== \"undefined\") module.exports = { KENTISH_BYLAWS };\n";
fs.writeFileSync("assets/bylaws-index.js", js);
console.log("Wrote assets/bylaws-index.js —", out.length, "bylaws,", out.reduce((a, b) => a + b.rules.length, 0), "rules");
